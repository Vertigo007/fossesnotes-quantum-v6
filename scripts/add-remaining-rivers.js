// Ajouter les rivières restantes à la base de données
async function addRemainingRivers() {
  try {
    console.log('🚀 Ajout des rivières restantes...');
    
    for (const riverData of remainingRivers) {
      // Vérifier si la rivière existe déjà
      const existingRiver = await Riviere.findOne({
        where: { nom: riverData.nom }
      });
      
      if (!existingRiver) {
        await Riviere.create(riverData);
        console.log(`✅ Rivière créée: ${riverData.nom}`);
      } else {
        console.log(`⚠️ Rivière déjà existante: ${riverData.nom}`);
      }
    }
    
    // Compter le total des rivières
    const totalRivieres = await Riviere.count();
    console.log(`\n📊 Total des rivières dans la base: ${totalRivieres}`);
    
    // Statistiques par province/état
    const stats = await Riviere.findAll({
      attributes: ['province_etat', [sequelize.fn('COUNT', sequelize.col('id')), 'count']],
      group: ['province_etat']
    });
    
    console.log('\n📈 Statistiques par province/état:');
    stats.forEach(stat => {
      console.log(`   - ${stat.province_etat}: ${stat.dataValues.count}`);
    });
    
    console.log('\n🎉 Ajout des rivières restantes terminé !');
    
  } catch (error) {
    console.error('❌ Erreur lors de l\'ajout des rivières restantes:', error);
  } finally {
    await sequelize.close();
  }
}

// Exécuter le script
addRemainingRivers();



