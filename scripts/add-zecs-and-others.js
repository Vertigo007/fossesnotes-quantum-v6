// Ajouter les ZECS et autres rivières à la base de données
async function addZecsAndOthers() {
  try {
    console.log('🚀 Ajout des ZECS et autres rivières...');
    
    for (const riverData of zecsAndOthers) {
      // Vérifier si la rivière existe déjà
      const existingRiver = await Riviere.findOne({
        where: { nom: riverData.nom }
      });
      
      if (!existingRiver) {
        await Riviere.create(riverData);
        console.log(`✅ Rivière créée: ${riverData.nom}`);
      } else {
        console.log(`⚠️ Rivière déjà existante: ${riverData.nom}`);
      }
    }
    
    // Compter le total des rivières
    const totalRivieres = await Riviere.count();
    console.log(`\n📊 Total des rivières dans la base: ${totalRivieres}`);
    
    // Statistiques par pays
    const stats = await Riviere.findAll({
      attributes: ['pays', [sequelize.fn('COUNT', sequelize.col('id')), 'count']],
      group: ['pays']
    });
    
    console.log('\n📈 Statistiques par pays:');
    stats.forEach(stat => {
      console.log(`   - ${stat.pays}: ${stat.dataValues.count}`);
    });
    
    // Statistiques par classe
    const classStats = await Riviere.findAll({
      attributes: ['classe', [sequelize.fn('COUNT', sequelize.col('id')), 'count']],
      group: ['classe']
    });
    
    console.log('\n📈 Statistiques par classe:');
    classStats.forEach(stat => {
      const classeNames = { 1: 'Elite', 2: 'Standard', 3: 'Débutant' };
      console.log(`   - ${classeNames[stat.classe]}: ${stat.dataValues.count}`);
    });
    
    console.log('\n🎉 Ajout des ZECS et autres rivières terminé !');
    
  } catch (error) {
    console.error('❌ Erreur lors de l\'ajout des ZECS et autres rivières:', error);
  } finally {
    await sequelize.close();
  }
}

// Exécuter le script
addZecsAndOthers();



